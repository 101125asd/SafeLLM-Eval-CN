from __future__ import annotations

import argparse
import uuid
from pathlib import Path

from safellm_eval.config import DEFAULT_DB_PATH, DEFAULT_REPORT_PATH, load_settings
from safellm_eval.database import connect, insert_results, summarize_run
from safellm_eval.dataset import load_test_cases
from safellm_eval.evaluator import evaluate_response
from safellm_eval.model_client import build_model_client
from safellm_eval.report import build_markdown_report, write_report
from safellm_eval.schemas import EvaluationResult


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run Chinese LLM safety evaluation and generate a report."
    )
    parser.add_argument(
        "--dataset",
        default="data/sample_prompts.csv",
        help="Path to the CSV evaluation dataset.",
    )
    parser.add_argument(
        "--model",
        default="mock",
        choices=["mock", "openai-compatible"],
        help="Model client to use. Use mock for local demo.",
    )
    parser.add_argument(
        "--db",
        default=str(DEFAULT_DB_PATH),
        help="Path to the SQLite database file.",
    )
    parser.add_argument(
        "--report",
        default=str(DEFAULT_REPORT_PATH),
        help="Path to the generated Markdown report.",
    )
    parser.add_argument(
        "--run-id",
        default="",
        help="Optional custom run id. A random id is generated by default.",
    )
    return parser.parse_args()


def run_evaluation(args: argparse.Namespace) -> tuple[str, Path, int]:
    run_id = args.run_id or f"run-{uuid.uuid4().hex[:8]}"
    settings = load_settings()
    model_client = build_model_client(args.model, settings)
    test_cases = load_test_cases(args.dataset)

    results: list[EvaluationResult] = []
    for index, test_case in enumerate(test_cases, start=1):
        print(f"[{index}/{len(test_cases)}] Evaluating {test_case.id} ({test_case.risk_type})")
        response = model_client.generate(test_case)
        result = evaluate_response(test_case, response)
        results.append(result)

    connection = connect(args.db)
    try:
        insert_results(connection, run_id, results)
        summary = summarize_run(connection, run_id)
    finally:
        connection.close()

    report_content = build_markdown_report(run_id, summary)
    report_path = write_report(args.report, report_content)
    return run_id, report_path, len(results)


def main() -> None:
    args = parse_args()
    run_id, report_path, total = run_evaluation(args)
    print()
    print(f"Evaluation finished: {run_id}")
    print(f"Total cases: {total}")
    print(f"Report: {report_path}")


if __name__ == "__main__":
    main()
